"""
How to make jury dialogue sound like real people
"""

print("❌ CURRENT ROBOTIC DIALOGUE:")
print("-" * 50)
print("'As an educator who spent years teaching critical thinking,")
print("what stands out immediately is the gap between the prosecution")
print("narrative and the actual evidence presented.'")

print("\n✓ REALISTIC DIALOGUE:")
print("-" * 50)
print("'Look, I teach high school, right? And one thing I always tell")
print("my kids - just cause something looks bad doesn't mean it IS bad.")
print("This footage... yeah, he's in the store. So what? I was in that")
print("same store yesterday. Doesn't make me a thief.'")

print("\n\nMORE EXAMPLES:")
print("=" * 50)

print("\n1. SKEPTICAL JUROR:")
print("ROBOTIC: 'Given my low trust in courts, I'm especially wary...'")
print("NATURAL: 'Listen, I don't trust cops much, okay? They mess up.'")

print("\n2. BUSINESS OWNER:")
print("ROBOTIC: 'As a small business owner, theft impacts my bottom line...'")
print("NATURAL: 'I run a shop downtown. People try this gift excuse all the time.'")

print("\n3. UNCERTAIN JUROR:")
print("ROBOTIC: 'I find myself torn between competing narratives...'")
print("NATURAL: 'I dunno, guys. Part of me thinks he did it, but... what if he didn't?'")

print("\n4. HEATED EXCHANGE:")
print("ROBOTIC:")
print("  A: 'I respectfully disagree with your assessment.'")
print("  B: 'Your position lacks evidentiary support.'")
print("\nNATURAL:")
print("  A: 'No way, that's not how it works!'")
print("  B: 'Then explain the receipt! Go on, I'm listening.'")

print("\n\nKEY PRINCIPLES:")
print("=" * 50)
print("• Use contractions (I'm, don't, can't)")
print("• Incomplete sentences ('But the thing is...')")
print("• Interruptions and false starts")
print("• Regional phrases and slang")
print("• Emotional reactions ('That's crazy!')")
print("• Personal anecdotes ('My cousin had this happen...')")
print("• Thinking out loud ('Wait, hold on... let me think...')")
print("• Direct address ('Sarah, you worked retail, right?')")

print("\n\nREAL JURY ROOM TALK:")
print("=" * 50)

print("\nElderly conservative juror:")
print("'Now hold on just a minute. Back in my day, if you took")
print("something without paying, that was stealing. Plain and simple.")
print("All this talk about maybe this, maybe that... the boy had")
print("stuff he didn't pay for. End of story.'")

print("\nYoung liberal juror:")
print("'Okay but like... we literally don't see him take anything?")
print("The whole case is basically he was there and had stuff.")
print("That's not enough to ruin someone's life over.'")

print("\nMiddle-aged working class:")
print("'Look, I work construction. I'm not some fancy lawyer. But")
print("even I can see there's holes in this case. Nobody saw nothing.")
print("That receipt thing? My wife loses receipts all the time.'")

print("\n\nHOW TO FIX THE PROMPTS:")
print("=" * 50)
print("ADD TO SYSTEM PROMPT:")
print("'Speak naturally like real people in conversation.'")
print("'Use contractions, incomplete sentences, and casual language.'")
print("'React emotionally. Interrupt. Think out loud.'")
print("'Reference your personal experiences.'")
print("'NO formal academic language or presentations.'")