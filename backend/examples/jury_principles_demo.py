"""
Demonstration of jury principles in action
"""

print("JURY DELIBERATION PRINCIPLES")
print("="*60)
print()

print("1. FOREPERSON READS JURY INSTRUCTIONS:")
print("-"*40)
print("""
As jurors, our goal is to:
1. Decide the facts based solely on evidence presented
2. Apply the law as instructed by the judge
3. Reach a verdict of guilty or not guilty
4. Remain impartial and disregard personal prejudices

The judge has instructed us that:
- The prosecution must prove guilt beyond a reasonable doubt
- The defendant is presumed innocent until proven guilty
- We must consider only the evidence presented in this case
- We should evaluate witness testimony and physical evidence carefully

During our deliberations:
- Keep an open mind until all evidence is considered
- Engage in respectful discussion and consider each other's views
- Work toward a unanimous verdict if possible
- Do not abandon your honest conviction, but be willing to change if compelling reasons are presented
- Avoid repetitive discussions - bring new insights when revisiting evidence
""")

print("\n2. MODERATION DURING DISCUSSION:")
print("-"*40)
print("Foreperson reminders:")
print("• 'Let's stay focused on the evidence presented in court.'")
print("• 'Remember, we must base our decision only on the evidence, not speculation.'")
print("• 'Keep in mind the prosecution must prove guilt beyond a reasonable doubt.'")
print("• 'We need compelling reasons to change our views, not just repetition.'")

print("\n3. VOTING INSTRUCTIONS:")
print("-"*40)
print("""
Before you vote, remember:
- The defendant is presumed innocent
- Guilt must be proven beyond a reasonable doubt
- Base your decision solely on the evidence presented
- Do not abandon your honest conviction without compelling reason
""")

print("\n4. JUROR BEHAVIOR GUIDELINES:")
print("-"*40)
print("Each juror must:")
print("• Reference specific evidence by number")
print("• Avoid repeating points unless adding new perspective")
print("• Explain WHY they agree/disagree based on their background")
print("• Only change views if given compelling evidence-based reasons")
print("• Keep responses concise (2-3 sentences)")

print("\n5. POST-VOTE PERSUASION:")
print("-"*40)
print("When split:")
print("• Each side presents evidence-based arguments")
print("• Focus on specific evidence that supports their position")
print("• No abandoning honest convictions without compelling reasons")
print("• Personality influences HOW they argue, not WHETHER they follow rules")

print("\n" + "="*60)
print("KEY PRINCIPLE: The law guides the process, personalities")
print("influence the dynamics, but evidence determines the outcome.")
print("="*60)